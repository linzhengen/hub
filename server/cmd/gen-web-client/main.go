// Command gen-web-client writes the web client's operation table from the API
// catalog.
//
// The browser client used to repeat every REST path as a template literal
// ("`/users/${id}`") next to a private copy of a query-string builder, so a path
// or parameter changed in a .proto stayed silently wrong in the UI until
// someone hit the endpoint. Generating the table means the paths, the path
// parameters and the HTTP verbs come from the same descriptors the server
// routes on, and a rename breaks the TypeScript build instead.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/linzhengen/hub/server/pkg/apicatalog"
)

func main() {
	out := flag.String("out", filepath.Join("..", "ui", "web", "src", "api", "operations.ts"),
		"path of the TypeScript file to write")
	base := flag.String("base", "/api/v1",
		"URL prefix the web client's fetch layer already applies, stripped from every generated path")
	flag.Parse()

	source, err := render(apicatalog.Default(), *base)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-web-client: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, source, 0o600); err != nil {
		fmt.Fprintf(os.Stderr, "gen-web-client: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("gen-web-client: wrote %s\n", *out)
}

func render(catalog *apicatalog.Catalog, base string) ([]byte, error) {
	buf := &bytes.Buffer{}
	fmt.Fprintf(buf, `// Code generated by server/cmd/gen-web-client. DO NOT EDIT.
//
// Paths are relative to %s, which fetchApi prepends.

export interface ApiOperation {
  readonly method: 'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH';
  readonly path: string;
  readonly pathParams: readonly string[];
}
`, base)

	exports := map[string]string{}
	for _, service := range catalog.Services() {
		name := exportName(service)
		if previous, taken := exports[name]; taken {
			return nil, fmt.Errorf("services %q and %q both generate the export %q", previous, service, name)
		}
		exports[name] = service

		fmt.Fprintf(buf, "\n/** Operations of %s. */\nexport const %s = {\n", service, name)
		for _, op := range catalog.OperationsOf(service) {
			if op.HTTPMethod == "" {
				continue
			}
			path, found := strings.CutPrefix(op.Path, base)
			if !found {
				return nil, fmt.Errorf("%s.%s is mapped to %q, which is outside the %q base; pass -base or give the web client its own fetch base",
					service, op.Method, op.Path, base)
			}
			// Placeholders are renamed to the field's JSON name so callers
			// address every parameter the same way the request bodies do.
			params := op.PathParams()
			for i, param := range params {
				field, ok := op.Field(param)
				if !ok {
					return nil, fmt.Errorf("%s.%s has path parameter %q with no matching request field", service, op.Method, param)
				}
				path = strings.ReplaceAll(path, "{"+param+"}", "{"+field.JSONName+"}")
				params[i] = field.JSONName
			}

			fmt.Fprintf(buf, "  /** %s */\n", op.Summary)
			fmt.Fprintf(buf, "  %s: { method: '%s', path: '%s', pathParams: [%s] },\n",
				lowerCamel(op.Method), op.HTTPMethod, path, quoteAll(params))
		}
		buf.WriteString("} as const satisfies Record<string, ApiOperation>;\n")
	}
	return buf.Bytes(), nil
}

// exportName turns "system.group.v1.GroupService" into "groupServiceOperations".
func exportName(service string) string {
	parts := strings.Split(service, ".")
	return lowerCamel(parts[len(parts)-1]) + "Operations"
}

func lowerCamel(name string) string {
	if name == "" {
		return name
	}
	runes := []rune(name)
	// Lower the leading run of capitals, keeping the last one when it starts
	// the next word: "ID" becomes "id" and "IDToken" becomes "idToken".
	for i, r := range runes {
		if !unicode.IsUpper(r) {
			if i > 1 {
				runes[i-1] = unicode.ToUpper(runes[i-1])
			}
			break
		}
		runes[i] = unicode.ToLower(r)
	}
	return string(runes)
}

func quoteAll(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, v := range values {
		quoted = append(quoted, "'"+v+"'")
	}
	return strings.Join(quoted, ", ")
}
