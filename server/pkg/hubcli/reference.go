package hubcli

import (
	"fmt"
	"strings"

	"github.com/linzhengen/hub/v1/server/pkg/apicatalog"
)

// RenderReference writes the Markdown API reference bundled with the agent
// skill. It is generated rather than written because a hand-kept reference is
// exactly the kind of document that quietly goes stale, and an agent following
// a stale reference produces confidently wrong calls.
func RenderReference(catalog *apicatalog.Catalog) string {
	var b strings.Builder

	b.WriteString("# hub API reference\n\n")
	b.WriteString("<!-- Generated by `hub api docs`. Run `make gen` to refresh; do not edit. -->\n\n")
	b.WriteString("Every operation below is reachable three ways:\n\n")
	b.WriteString("- the generated command, e.g. `hub user list-user --limit 10`\n")
	b.WriteString("- the REST endpoint, e.g. `hub api call GET /api/v1/users --query limit=10`\n")
	b.WriteString("- the gRPC method, for a generated client\n\n")
	b.WriteString("`rbac` is the permission the caller needs: the verb (`action`) on the\n")
	b.WriteString("resource identifier. A role granting `*` on `api.*` covers everything.\n")

	for _, service := range catalog.Services() {
		fmt.Fprintf(&b, "\n## %s\n", service)

		for _, op := range catalog.OperationsOf(service) {
			if op.HTTPMethod == "" {
				continue
			}
			fmt.Fprintf(&b, "\n### %s\n\n", op.Method)
			if op.Summary != "" {
				fmt.Fprintf(&b, "%s\n\n", op.Summary)
			}
			fmt.Fprintf(&b, "- command: `hub %s %s`\n", GroupName(op), CommandName(op))
			fmt.Fprintf(&b, "- endpoint: `%s %s`\n", op.HTTPMethod, op.Path)
			if op.Public {
				b.WriteString("- rbac: none, any authenticated caller may use this rpc\n")
			} else {
				fmt.Fprintf(&b, "- rbac: `%s` on `%s`\n", op.Action, op.Resource)
			}
			writeFieldTable(&b, op)
		}
	}
	return b.String()
}

func writeFieldTable(b *strings.Builder, op apicatalog.Operation) {
	if len(op.Fields) == 0 {
		b.WriteString("\nTakes no parameters.\n")
		return
	}

	b.WriteString("\n| flag | field | in | type | rules |\n| --- | --- | --- | --- | --- |\n")
	for _, field := range op.Fields {
		fmt.Fprintf(b, "| `--%s` | `%s` | %s | %s | %s |\n",
			FlagName(field), field.JSONName, field.In, fieldType(field), strings.Join(field.Constraints, ", "))
	}
}

func fieldType(field apicatalog.Field) string {
	kind := field.Kind
	if len(field.EnumValues) > 0 {
		kind = "`" + strings.Join(field.EnumValues, "` \\| `") + "`"
	}
	if field.Repeated {
		return "repeated " + kind
	}
	return kind
}
